// Writes src/creds.ts (gitignored) from ../ai-gram/aircrew.keys.json — the same official Aircrew
// api_id/api_hash the Mac app bundles. Never commit or print the output.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
const src = new URL('../../ai-gram/aircrew.keys.json', import.meta.url)
let apiId = null, apiHash = null
if (existsSync(src)) {
  const k = JSON.parse(readFileSync(src, 'utf8'))
  apiId = Number(k.apiId ?? k.api_id ?? k.TELEGRAM_API_ID) || null
  apiHash = String(k.apiHash ?? k.api_hash ?? k.TELEGRAM_API_HASH ?? '') || null
}
writeFileSync(new URL('../src/creds.ts', import.meta.url),
  `// AUTO-GENERATED by scripts/gen-creds.mjs — do not edit, do not commit.\nexport const CREDS = ${JSON.stringify({ apiId, apiHash })} as const\n`)
console.log(apiId ? 'creds: ok' : 'creds: MISSING (aircrew.keys.json not found)')
